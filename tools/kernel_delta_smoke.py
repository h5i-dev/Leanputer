"""Focused stock validation of the general checked-definition reduction module.

Reference execution is offline diagnostics only. No reference answers enter
NativeMachine.check. Four probes cover neutral opacity, delta/beta application
spines and generic universe zip; longer metadata/two-arg contract remains IR.
"""
import argparse
from pathlib import Path
import torch
from leanputer.kernel import source_transition as program
from leanputer.kernel.traversal_machine import MachineConfig
from tests.test_kernel_delta_transition import cases
from tools.kernel_level_smoke import run_smoke


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--device',default='cuda',choices=('cpu','cuda'))
    parser.add_argument('--report',type=Path,required=True)
    args=parser.parse_args()
    torch.set_num_threads(1)
    cfg=MachineConfig(heap=256,stack=16,context=8,constants=4,fuel=512,word_bits=9)
    run_smoke(cfg,cases()[:4],program,args.device,args.report,'checked-delta',
        '4 focused generic checked-definition reduction probes; every private signature generated by weighted source checks; '
        'delta/beta application spine and original universe schemes; complete inductive/recursor/primitives/conversion unfinished',
        early_stop=True)


if __name__=='__main__':main()
