"""Compile generic family grouping and private recursor metadata publication."""
from .native_cells import CellTag,VectorKind
from .traversal_machine import (Mode,Task,Outcome,Reason,CALL_ASM_FAMILIES,
    CALL_ASM_RULES,CALL_ASM_SIGNATURES)

PRIVATE_PHASES=(CALL_ASM_FAMILIES,CALL_ASM_RULES,CALL_ASM_SIGNATURES)
NO_NODE=(Mode.WALK,Mode.ASM_FAMILY_LINK,Mode.ASM_BLOCK,Mode.ASM_AUX,Mode.ASM_RULE_STORE,
    Mode.ASM_COUNTS,Mode.ASM_RECURSOR,Mode.ASM_STORE_SCHEME,Mode.ASM_SIGNATURE,Mode.ASM_LINK,Mode.ASM_SIG_ORDER)
TAGS={Mode.ASM_NAMES:CellTag.VALIDATED_RECURSOR_NAME,Mode.ASM_VECTOR:CellTag.VECTOR,
    Mode.ASM_CELL:CellTag.VECTOR_CELL,Mode.ASM_TYPE:CellTag.RECURSOR_TYPE,Mode.ASM_OWNER:CellTag.CHECKED_SIGNATURE,
    Mode.ASM_SCHEME:CellTag.CHECKED_SCHEME,Mode.ASM_HEADER:CellTag.CHECKED_FAMILY,
    Mode.ASM_RAW_FAMILY:CellTag.RAW_FAMILY,Mode.ASM_RAW_AUX:CellTag.RAW_FAMILY_AUX,
    Mode.ASM_CTOR_VECTOR:CellTag.VECTOR,Mode.ASM_RULE_VECTOR:CellTag.VECTOR,
    Mode.ASM_RULE_CELL:CellTag.VECTOR_CELL,Mode.ASM_RULE_INFO:CellTag.FAMILY_RULE}


def emit_rules(c):
    r,n,f=c.r,c.read['node'],c.read['frame'];top=c.sub(r['sp'],1)
    returning=c.AND(c.mode(Mode.RETURN),c.NOT(c.eq(r['sp'],0)))
    phase=lambda p:c.AND(returning,c.eq(f['phase'],p))
    def reverse(guard,p,head,count):
        c.write('stack',guard,top,(p,0,0,Task.ASSEMBLE_RECURSORS,0,0))
        c.emit(guard,task=Task.REVERSE_LIST,mode=Mode.WALK,x=head,reverse_length=count,depth=0)
    def advance_rule(guard,head=None,count=None):
        more=c.lt(1,r['asm_rule_remaining']);c.emit(guard,asm_rule_remaining=c.sub(r['asm_rule_remaining'],1))
        c.emit(c.AND(guard,more),mode=Mode.ASM_RULE_CELL,x=r['asm_rule_next'])
        reverse(c.AND(guard,c.NOT(more)),CALL_ASM_RULES,r['asm_group_rev'] if head is None else head,r['asm_group_count'] if count is None else count)
    c.emit(phase(CALL_ASM_FAMILIES),task=Task.ASSEMBLE_RECURSORS,core_family_vector=r['r'],mode=Mode.ASM_BLOCK)
    grouped=phase(CALL_ASM_RULES);valid=c.eq(r['asm_group_count'],r['asm_expected'])
    c.stop(c.AND(grouped,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(grouped,valid),task=Task.ASSEMBLE_RECURSORS,asm_group=r['r'],mode=Mode.ASM_COUNTS)
    done=phase(CALL_ASM_SIGNATURES);c.emit(done,task=Task.ASSEMBLE_RECURSORS,core_rec_signatures=r['r'],sp=top);c.ret(done,r['r'])
    active=c.task(Task.ASSEMBLE_RECURSORS);at=lambda m:c.AND(active,c.mode(m))
    def room(guard,size=1):
        wide=c.g.add(c.g.fit(r['free'],c.width+1),c.g.const(size,c.width+1));fits=c.NOT(c.g.lt(c.g.const(c.cfg.heap,c.width+1),wide))
        c.stop(c.AND(guard,c.NOT(fits)),Outcome.RESOURCE,Reason.HEAP)
        return c.AND(guard,fits)
    init=at(Mode.WALK);valid=c.AND(*(c.NOT(c.eq(r[key],0)) for key in ('core_rules','core_rec_types','core_flags','typing_active','header_seen')));stackroom=c.lt(r['sp'],c.cfg.stack)
    c.stop(c.AND(init,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    c.stop(c.AND(init,valid,c.NOT(stackroom)),Outcome.RESOURCE,Reason.STACK);init=c.AND(init,valid,stackroom)
    c.write('stack',init,r['sp'],(CALL_ASM_FAMILIES,0,0,Task.ASSEMBLE_RECURSORS,0,0))
    c.emit(init,sp=c.add(r['sp'],1),asm_names_remaining=r['header_seen'],asm_family_rev=0,asm_sig_rev=0,mode=Mode.ASM_NAMES,x=r['core_rec_names'])
    names=at(Mode.ASM_NAMES);valid=c.AND(c.NOT(c.eq(r['asm_names_remaining'],0)),c.eq(c.mux(c.eq(n['c'],0),0,1),c.mux(c.lt(1,r['asm_names_remaining']),1,0)))
    c.stop(c.AND(names,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(names,valid),asm_family_value=n['a'],asm_name_next=n['c'],mode=Mode.ASM_FAMILY_LINK)
    link=room(at(Mode.ASM_FAMILY_LINK));more=c.lt(1,r['asm_names_remaining'])
    c.write('heap',link,r['free'],(CellTag.VECTOR_CELL,r['asm_family_value'],r['asm_family_rev'],0))
    c.emit(link,free=c.add(r['free'],1),asm_family_rev=r['free'],asm_names_remaining=c.sub(r['asm_names_remaining'],1))
    c.emit(c.AND(link,more),mode=Mode.ASM_NAMES,x=r['asm_name_next'])
    reverse(c.AND(link,c.NOT(more)),CALL_ASM_FAMILIES,r['free'],r['header_seen'])
    block=room(at(Mode.ASM_BLOCK),2)
    c.write('heap',block,r['free'],(CellTag.RECURSOR_BLOCK,r['core_K'],r['core_flags'],r['core_family_vector']))
    c.emit(block,free=c.add(r['free'],1),asm_block=r['free'],mode=Mode.ASM_AUX)
    aux=at(Mode.ASM_AUX);c.write('heap',aux,r['free'],(CellTag.RECURSOR_SHARED_COUNTS,r['header_seen'],r['core_ctor_declared'],r['asm_block']))
    c.emit(aux,free=c.add(r['free'],1),asm_aux=r['free'],mode=Mode.ASM_VECTOR,x=r['core_rec_types'])
    shape=lambda:c.AND(c.eq(n['c'],VectorKind.REFERENCES),c.eq(c.mux(c.eq(n['a'],0),0,1),c.mux(c.eq(n['b'],0),0,1)))
    vector=at(Mode.ASM_VECTOR);valid=c.AND(shape(),c.NOT(c.eq(n['a'],0)),c.eq(n['a'],r['header_seen']))
    c.stop(c.AND(vector,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(vector,valid),asm_remaining=n['a'],mode=Mode.ASM_CELL,x=n['b'])
    def cell_guard(mode,remaining):
        cell=at(mode);valid=c.AND(c.NOT(c.eq(r[remaining],0)),c.eq(c.mux(c.eq(n['b'],0),0,1),c.mux(c.lt(1,r[remaining]),1,0)))
        c.stop(c.AND(cell,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
        return c.AND(cell,valid)
    c.emit(cell_guard(Mode.ASM_CELL,'asm_remaining'),asm_next=n['b'],mode=Mode.ASM_TYPE,x=n['a'])
    c.emit(at(Mode.ASM_TYPE),asm_family=n['a'],asm_type=n['b'],asm_symbol=n['c'],asm_group_rev=0,asm_group_count=0,mode=Mode.ASM_OWNER,x=n['a'])
    c.emit(at(Mode.ASM_OWNER),mode=Mode.ASM_SCHEME,x=n['c'])
    scheme=at(Mode.ASM_SCHEME);valid=c.eq(n['b'],8)
    c.stop(c.AND(scheme,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(scheme,valid),mode=Mode.ASM_HEADER,x=n['c'])
    c.emit(at(Mode.ASM_HEADER),asm_indices=n['a'],mode=Mode.ASM_RAW_FAMILY,x=n['c'])
    c.emit(at(Mode.ASM_RAW_FAMILY),mode=Mode.ASM_RAW_AUX,x=n['c'])
    c.emit(at(Mode.ASM_RAW_AUX),mode=Mode.ASM_CTOR_VECTOR,x=n['a'])
    vector=at(Mode.ASM_CTOR_VECTOR);valid=shape()
    c.stop(c.AND(vector,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(vector,valid),asm_expected=n['a'],mode=Mode.ASM_RULE_VECTOR,x=r['core_rules'])
    vector=at(Mode.ASM_RULE_VECTOR);valid=c.AND(shape(),c.eq(n['a'],r['core_ctor_declared']))
    c.stop(c.AND(vector,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    reverse(c.AND(vector,valid,c.eq(n['a'],0)),CALL_ASM_RULES,0,0)
    c.emit(c.AND(vector,valid,c.NOT(c.eq(n['a'],0))),asm_rule_remaining=n['a'],mode=Mode.ASM_RULE_CELL,x=n['b'])
    c.emit(cell_guard(Mode.ASM_RULE_CELL,'asm_rule_remaining'),asm_rule_next=n['b'],mode=Mode.ASM_RULE_INFO,x=n['a'])
    info=at(Mode.ASM_RULE_INFO);match=c.eq(n['a'],r['asm_family'])
    c.emit(c.AND(info,match),asm_rule_ref=n['b'],mode=Mode.ASM_RULE_STORE);advance_rule(c.AND(info,c.NOT(match)))
    store=room(at(Mode.ASM_RULE_STORE));count=c.add(r['asm_group_count'],1)
    c.write('heap',store,r['free'],(CellTag.VECTOR_CELL,r['asm_rule_ref'],r['asm_group_rev'],0))
    c.emit(store,free=c.add(r['free'],1),asm_group_rev=r['free'],asm_group_count=count);advance_rule(store,r['free'],count)
    counts=room(at(Mode.ASM_COUNTS),6)
    c.write('heap',counts,r['free'],(CellTag.RECURSOR_COUNTS,r['header_parameter_count'],r['asm_indices'],r['asm_aux']))
    c.emit(counts,free=c.add(r['free'],1),asm_counts=r['free'],mode=Mode.ASM_RECURSOR)
    rec=at(Mode.ASM_RECURSOR);c.write('heap',rec,r['free'],(CellTag.CHECKED_RECURSOR,r['asm_family'],r['asm_counts'],r['asm_group']))
    c.emit(rec,free=c.add(r['free'],1),asm_rec=r['free'],mode=Mode.ASM_STORE_SCHEME)
    scheme=at(Mode.ASM_STORE_SCHEME);c.write('heap',scheme,r['free'],(CellTag.CHECKED_SCHEME,r['core_rec_parameters'],10,r['asm_rec']))
    c.emit(scheme,free=c.add(r['free'],1),asm_scheme=r['free'],mode=Mode.ASM_SIGNATURE)
    signature=at(Mode.ASM_SIGNATURE);c.write('heap',signature,r['free'],(CellTag.CHECKED_SIGNATURE,r['asm_symbol'],r['asm_type'],r['asm_scheme']))
    c.emit(signature,free=c.add(r['free'],1),asm_signature=r['free'],mode=Mode.ASM_LINK)
    link=at(Mode.ASM_LINK);c.write('heap',link,r['free'],(CellTag.VECTOR_CELL,r['asm_signature'],r['typing_head'],0))
    c.emit(link,free=c.add(r['free'],1),typing_head=r['free'],mode=Mode.ASM_SIG_ORDER)
    order=at(Mode.ASM_SIG_ORDER);more=c.lt(1,r['asm_remaining'])
    c.write('heap',order,r['free'],(CellTag.VECTOR_CELL,r['asm_signature'],r['asm_sig_rev'],0))
    c.emit(order,free=c.add(r['free'],1),asm_sig_rev=r['free'],asm_remaining=c.sub(r['asm_remaining'],1))
    c.emit(c.AND(order,more),mode=Mode.ASM_CELL,x=r['asm_next'])
    reverse(c.AND(order,c.NOT(more)),CALL_ASM_SIGNATURES,r['free'],r['header_seen'])
