"""Lower complete source family/head/level/parameter/index application predicate."""
from .arena import Tag
from .native_cells import CellTag,VectorKind
from .traversal_machine import (Mode,Task,Outcome,Reason,CALL_APP_MEMBER,CALL_APP_LOOKUP,
    CALL_APP_LEVELS,CALL_APP_INDEX,CALL_APP_PARAMETER)

PRIVATE_PHASES=tuple(range(CALL_APP_MEMBER,CALL_APP_PARAMETER+1))


def emit_rules(c):
    r,n,f=c.r,c.read['node'],c.read['frame'];a,b=n['a'],n['b'];top=c.sub(r['sp'],1)
    returning=c.AND(c.mode(Mode.RETURN),c.NOT(c.eq(r['sp'],0)))
    at=lambda phase:c.AND(returning,c.eq(f['phase'],phase))
    def no(guard):c.emit(guard,sp=top);c.ret(guard,0)
    def yes(guard):c.emit(guard,sp=top);c.ret(guard,r['app_signature'])
    def call(guard,phase,task,x,**updates):
        c.write('stack',guard,top,(phase,0,0,Task.FAMILY_APPLICATION,0,0))
        c.emit(guard,task=task,mode=Mode.WALK,x=x,depth=0,**updates)
    member=at(CALL_APP_MEMBER)
    no(c.AND(member,c.eq(r['r'],0)))
    call(c.AND(member,c.NOT(c.eq(r['r'],0))),CALL_APP_LOOKUP,Task.ENV_LOOKUP,0,
        query_symbol=r['app_symbol'],lookup_head=r['header_head'])
    lookup=at(CALL_APP_LOOKUP)
    c.stop(c.AND(lookup,c.eq(r['r'],0)),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(lookup,c.NOT(c.eq(r['r'],0))),task=Task.FAMILY_APPLICATION,mode=Mode.APP_SIGNATURE,x=r['r'],app_signature=r['r'])
    levels=at(CALL_APP_LEVELS);nonempty=c.NOT(c.eq(r['app_arity'],0))
    no(c.AND(levels,c.eq(r['r'],0)))
    yes(c.AND(levels,c.NOT(c.eq(r['r'],0)),c.NOT(nonempty)))
    c.emit(c.AND(levels,c.NOT(c.eq(r['r'],0)),nonempty),task=Task.FAMILY_APPLICATION,mode=Mode.APP_ARGUMENT,
        x=r['app_args'],app_remaining=r['app_arity'],app_context_index=r['header_parameter_base'])
    for phase in (CALL_APP_INDEX,CALL_APP_PARAMETER):
        returned=at(phase);invalid=c.NOT(c.eq(r['r'],0)) if phase==CALL_APP_INDEX else c.eq(r['r'],0)
        no(c.AND(returned,invalid))
        valid=c.AND(returned,c.NOT(invalid));last=c.eq(r['app_remaining'],1)
        yes(c.AND(valid,last))
        c.emit(c.AND(valid,c.NOT(last)),task=Task.FAMILY_APPLICATION,mode=Mode.APP_ARGUMENT,x=r['app_next'],app_remaining=c.sub(r['app_remaining'],1))
        if phase==CALL_APP_PARAMETER:c.emit(c.AND(valid,c.NOT(last)),app_context_index=c.add(r['app_context_index'],1))
    active=c.task(Task.FAMILY_APPLICATION);at_mode=lambda mode:c.AND(active,c.mode(mode))
    c.emit(at_mode(Mode.WALK),mode=Mode.APP_SPINE,app_args=0,app_arity=0)
    spine=at_mode(Mode.APP_SPINE);app=c.tag(Tag.APP);constant=c.tag(Tag.CONST)
    room=c.lt(r['free'],c.cfg.heap)
    c.stop(c.AND(spine,app,c.NOT(room)),Outcome.RESOURCE,Reason.HEAP)
    store=c.AND(spine,app,room)
    c.write('heap',store,r['free'],(CellTag.VECTOR_CELL,b,r['app_args'],0))
    c.emit(store,free=c.add(r['free'],1),app_args=r['free'],app_arity=c.add(r['app_arity'],1),x=a)
    c.ret(c.AND(spine,c.NOT(app),c.NOT(constant)),0)
    stack_room=c.lt(r['sp'],c.cfg.stack)
    c.stop(c.AND(spine,constant,c.NOT(stack_room)),Outcome.RESOURCE,Reason.STACK)
    enter=c.AND(spine,constant,stack_room)
    c.write('stack',enter,r['sp'],(CALL_APP_MEMBER,0,0,Task.FAMILY_APPLICATION,0,0))
    c.emit(enter,sp=c.add(r['sp'],1),app_symbol=a,app_levels=b,task=Task.HAS_FAMILIES,mode=Mode.WALK)
    c.emit(at_mode(Mode.APP_SIGNATURE),mode=Mode.APP_SCHEME,x=n['c'])
    scheme=at_mode(Mode.APP_SCHEME)
    c.stop(c.AND(scheme,c.NOT(c.eq(b,8))),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(scheme,c.eq(b,8)),mode=Mode.APP_METADATA,x=n['c'])
    metadata=at_mode(Mode.APP_METADATA)
    expected=c.g.add(c.g.fit(c.sub(r['header_parameter_end'],r['header_parameter_base']),c.width+1),c.g.fit(a,c.width+1))
    arity=c.g.eq(c.g.fit(r['app_arity'],c.width+1),expected)
    no(c.AND(metadata,c.NOT(arity)))
    call(c.AND(metadata,arity),CALL_APP_LEVELS,Task.VECTOR_EQUAL,r['app_levels'],peer=r['header_levels'],vector_expected_role=VectorKind.LEVELS)
    argument=at_mode(Mode.APP_ARGUMENT);more=c.lt(1,r['app_remaining'])
    valid=c.AND(c.NOT(c.eq(r['app_remaining'],0)),c.eq(c.mux(c.eq(b,0),0,1),c.mux(more,1,0)),c.NOT(c.eq(a,0)),c.lt(a,r['free']))
    c.stop(c.AND(argument,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    argument=c.AND(argument,valid)
    c.emit(argument,app_argument=a,app_next=b)
    parameter=c.lt(r['app_context_index'],r['header_parameter_end'])
    c.emit(c.AND(argument,parameter),mode=Mode.APP_PARAMETER_SELECT,x=a)
    call(c.AND(argument,c.NOT(parameter)),CALL_APP_INDEX,Task.HAS_FAMILIES,a)
    c.emit(at_mode(Mode.APP_PARAMETER_SELECT),mode=Mode.APP_PARAMETER_RECORD,x=c.read['operand']['value'])
    record=at_mode(Mode.APP_PARAMETER_RECORD);valid=c.AND(c.NOT(c.eq(a,0)),c.lt(a,r['free']))
    c.stop(c.AND(record,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    call(c.AND(record,valid),CALL_APP_PARAMETER,Task.EXPR_EQUAL,r['app_argument'],peer=a)
