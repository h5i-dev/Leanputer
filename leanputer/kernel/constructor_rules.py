"""Lower generic typed constructor CORE traversal; pending names are not types."""
from .arena import Tag
from .native_cells import CellTag,VectorKind
from .traversal_machine import (Mode,Task,Outcome,Reason,CALL_CTOR_NAME,CALL_CTOR_DUPLICATE_DECLARATION,
    CALL_CTOR_DUPLICATE_PENDING,CALL_CTOR_SCOPE,CALL_CTOR_INFER,CALL_CTOR_TYPE_WHNF,CALL_CTOR_CONSUME,
    CALL_CTOR_FIELD_INFER,CALL_CTOR_FIELD_WHNF,CALL_CTOR_RESULT_PROP,CALL_CTOR_FIELD_LEVEL,
    CALL_CTOR_POSITIVITY,CALL_CTOR_RECURSIVE,CALL_CTOR_OPEN_FIELD,CALL_CTOR_RESULT_APPLICATION,CALL_CTOR_FIELD_VECTOR)

PRIVATE_PHASES=tuple(range(CALL_CTOR_NAME,CALL_CTOR_FIELD_VECTOR+1))


def emit_rules(c):
    r,n,f=c.r,c.read['node'],c.read['frame'];a,b=n['a'],n['b'];top=c.sub(r['sp'],1)
    returning=c.AND(c.mode(Mode.RETURN),c.NOT(c.eq(r['sp'],0)))
    at=lambda phase:c.AND(returning,c.eq(f['phase'],phase))
    def call(guard,phase,task,x,mode=Mode.WALK,**updates):
        c.write('stack',guard,top,(phase,0,0,Task.CHECK_CONSTRUCTORS,0,0))
        c.emit(guard,task=task,x=x,mode=mode,depth=0,**updates)
    def positivity(guard):call(guard,CALL_CTOR_POSITIVITY,Task.CHECK_POSITIVITY,r['ctor_field_domain'])
    call(at(CALL_CTOR_NAME),CALL_CTOR_DUPLICATE_DECLARATION,Task.ENV_LOOKUP,0,query_symbol=r['ctor_symbol'],lookup_head=r['typing_head'])
    for phase in (CALL_CTOR_DUPLICATE_DECLARATION,CALL_CTOR_DUPLICATE_PENDING):
        c.stop(c.AND(at(phase),c.NOT(c.eq(r['r'],0))),Outcome.INVALID,Reason.DUPLICATE_DECLARATION)
    call(c.AND(at(CALL_CTOR_DUPLICATE_DECLARATION),c.eq(r['r'],0)),CALL_CTOR_DUPLICATE_PENDING,Task.ENV_LOOKUP,0,
        query_symbol=r['ctor_symbol'],lookup_head=r['ctor_names'])
    call(c.AND(at(CALL_CTOR_DUPLICATE_PENDING),c.eq(r['r'],0)),CALL_CTOR_SCOPE,Task.EXPR_SCOPE,r['ctor_type'])
    call(at(CALL_CTOR_SCOPE),CALL_CTOR_INFER,Task.INFER,r['ctor_type'],local_base=r['header_parameter_base'])
    call(at(CALL_CTOR_INFER),CALL_CTOR_TYPE_WHNF,Task.BETA_ZETA,r['r'],Mode.BETA_ZETA)
    c.emit(at(CALL_CTOR_TYPE_WHNF),task=Task.CHECK_CONSTRUCTORS,mode=Mode.CTOR_TYPE_SORT,x=r['r'])
    c.emit(at(CALL_CTOR_CONSUME),task=Task.CHECK_CONSTRUCTORS,mode=Mode.CTOR_FIELDS,x=r['r'])
    call(at(CALL_CTOR_FIELD_INFER),CALL_CTOR_FIELD_WHNF,Task.BETA_ZETA,r['r'],Mode.BETA_ZETA)
    c.emit(at(CALL_CTOR_FIELD_WHNF),task=Task.CHECK_CONSTRUCTORS,mode=Mode.CTOR_FIELD_SORT,x=r['r'])
    proposition=at(CALL_CTOR_RESULT_PROP)
    positivity(c.AND(proposition,c.NOT(c.eq(r['r'],0))))
    call(c.AND(proposition,c.eq(r['r'],0)),CALL_CTOR_FIELD_LEVEL,Task.LEVEL_GEQ,r['header_result_level'],peer=r['ctor_field_level'])
    bound=at(CALL_CTOR_FIELD_LEVEL)
    c.stop(c.AND(bound,c.eq(r['r'],0)),Outcome.INVALID,Reason.UNIVERSE)
    positivity(c.AND(bound,c.NOT(c.eq(r['r'],0))))
    positive=at(CALL_CTOR_POSITIVITY)
    c.stop(c.AND(positive,c.eq(r['r'],0)),Outcome.INVALID,Reason.INVALID_INDUCTIVE_APPLICATION)
    call(c.AND(positive,c.NOT(c.eq(r['r'],0))),CALL_CTOR_RECURSIVE,Task.RECURSIVE_ARGUMENT,r['ctor_field_domain'])
    recursive=at(CALL_CTOR_RECURSIVE)
    c.emit(recursive,ctor_recursive=r['r'])
    call(recursive,CALL_CTOR_OPEN_FIELD,Task.OPEN_TELESCOPE,r['ctor_active_pi'],Mode.TELESCOPE,
        open_tag=Tag.PI,bounded=1,limit=c.add(r['ctx'],1))
    c.emit(at(CALL_CTOR_OPEN_FIELD),task=Task.CHECK_CONSTRUCTORS,mode=Mode.CTOR_FIELD_SELECT,x=r['r'],ctor_field_tail=r['r'])
    application=at(CALL_CTOR_RESULT_APPLICATION)
    owner=c.AND(c.NOT(c.eq(r['r'],0)),c.eq(r['r'],r['ctor_family_signature']))
    c.stop(c.AND(application,c.NOT(owner)),Outcome.INVALID,Reason.INVALID_INDUCTIVE_APPLICATION)
    c.emit(c.AND(application,owner),ctor_result_args=r['app_args'])
    call(c.AND(application,owner),CALL_CTOR_FIELD_VECTOR,Task.REVERSE_LIST,r['ctor_field_rev'],reverse_length=r['ctor_field_count'])
    c.emit(at(CALL_CTOR_FIELD_VECTOR),task=Task.CHECK_CONSTRUCTORS,mode=Mode.CTOR_STORE_META,ctor_field_vector=r['r'])
    active=c.task(Task.CHECK_CONSTRUCTORS);at_mode=lambda mode:c.AND(active,c.mode(mode))
    def family_done(guard,names=None):
        more=c.lt(1,r['ctor_families_remaining'])
        c.emit(guard,ctor_families_remaining=c.sub(r['ctor_families_remaining'],1),ctx=r['header_parameter_end'])
        c.emit(c.AND(guard,more),mode=Mode.CTOR_FAMILY_CELL,x=r['ctor_family_next'])
        c.emit(c.AND(guard,c.NOT(more)),sp=top)
        c.ret(c.AND(guard,c.NOT(more)),r['ctor_names'] if names is None else names)
    init=at_mode(Mode.WALK);nonempty=c.NOT(c.eq(r['header_seen'],0));room=c.lt(r['sp'],c.cfg.stack)
    c.stop(c.AND(init,c.NOT(nonempty)),Outcome.INVALID,Reason.INVALID_DECLARATION)
    c.stop(c.AND(init,nonempty,c.NOT(room)),Outcome.RESOURCE,Reason.STACK)
    init=c.AND(init,nonempty,room)
    c.write('stack',init,r['sp'],(CALL_CTOR_NAME,0,0,Task.CHECK_CONSTRUCTORS,0,0))
    c.emit(init,sp=c.add(r['sp'],1),typing_active=1,typing_head=r['header_head'],ctor_names=0,
        ctor_families_remaining=r['header_seen'],mode=Mode.CTOR_FAMILY_CELL,x=r['header_head'])
    c.emit(at_mode(Mode.CTOR_FAMILY_CELL),ctor_family_next=b,mode=Mode.CTOR_FAMILY_SIGNATURE,x=a)
    c.emit(at_mode(Mode.CTOR_FAMILY_SIGNATURE),ctor_family_signature=r['x'],mode=Mode.CTOR_FAMILY_SCHEME,x=n['c'])
    scheme=at_mode(Mode.CTOR_FAMILY_SCHEME)
    c.stop(c.AND(scheme,c.NOT(c.eq(b,8))),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(scheme,c.eq(b,8)),mode=Mode.CTOR_FAMILY_METADATA,x=n['c'])
    c.emit(at_mode(Mode.CTOR_FAMILY_METADATA),mode=Mode.CTOR_RAW_FAMILY,x=n['c'])
    c.emit(at_mode(Mode.CTOR_RAW_FAMILY),mode=Mode.CTOR_FAMILY_AUX,x=n['c'])
    c.emit(at_mode(Mode.CTOR_FAMILY_AUX),mode=Mode.CTOR_VECTOR,x=a)
    vector=at_mode(Mode.CTOR_VECTOR)
    shape=c.AND(c.eq(n['c'],VectorKind.REFERENCES),c.eq(c.mux(c.eq(a,0),0,1),c.mux(c.eq(b,0),0,1)))
    c.stop(c.AND(vector,c.NOT(shape)),Outcome.INVALID,Reason.SYNTAX)
    family_done(c.AND(vector,shape,c.eq(a,0)))
    c.emit(c.AND(vector,shape,c.NOT(c.eq(a,0))),ctor_remaining=a,mode=Mode.CTOR_CELL,x=b)
    cell=at_mode(Mode.CTOR_CELL);more=c.lt(1,r['ctor_remaining'])
    shape=c.AND(c.NOT(c.eq(r['ctor_remaining'],0)),c.eq(c.mux(c.eq(b,0),0,1),c.mux(more,1,0)))
    c.stop(c.AND(cell,c.NOT(shape)),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(cell,shape),ctor_next=b,mode=Mode.CTOR_RECORD,x=a)
    ptr=lambda p:c.AND(c.NOT(c.eq(p,0)),c.lt(p,r['free']))
    record=at_mode(Mode.CTOR_RECORD);valid=c.AND(c.NOT(c.eq(a,0)),ptr(b))
    c.stop(c.AND(record,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    record=c.AND(record,valid)
    c.emit(record,ctor_symbol=a,ctor_type=b,ctor_field_count=0,ctor_field_rev=0,ctx=r['header_parameter_end'])
    call(record,CALL_CTOR_NAME,Task.CHECK_NAME,r['symbols_root'],query_symbol=a)
    def ensure_sort(guard):
        stable=c.tag(Tag.PI,Tag.LAM,Tag.BVAR,Tag.LOCAL,Tag.NAT,Tag.STRING)
        c.stop(c.AND(guard,c.NOT(c.tag(Tag.SORT)),stable),Outcome.INVALID,Reason.EXPECT_SORT)
        c.stop(c.AND(guard,c.NOT(c.tag(Tag.SORT)),c.NOT(stable)),Outcome.GAP,Reason.GAP_CONVERSION)
        return c.AND(guard,c.tag(Tag.SORT))
    typed=ensure_sort(at_mode(Mode.CTOR_TYPE_SORT))
    call(typed,CALL_CTOR_CONSUME,Task.CONSUME_PARAMETERS,r['ctor_type'],
        reuse_base=r['header_parameter_base'],reuse_end=r['header_parameter_end'],reuse_whnf=0)
    field=at_mode(Mode.CTOR_FIELDS);pi=c.tag(Tag.PI)
    c.emit(c.AND(field,pi),ctor_active_pi=r['x'],ctor_field_domain=a)
    call(c.AND(field,pi),CALL_CTOR_FIELD_INFER,Task.INFER,a,local_base=r['header_parameter_base'])
    call(c.AND(field,c.NOT(pi)),CALL_CTOR_RESULT_APPLICATION,Task.FAMILY_APPLICATION,r['x'])
    sorted_=ensure_sort(at_mode(Mode.CTOR_FIELD_SORT))
    c.emit(sorted_,ctor_field_level=a)
    call(sorted_,CALL_CTOR_RESULT_PROP,Task.LEVEL_EQUIVALENT,r['header_result_level'],peer=r['kernel_zero'])
    c.emit(at_mode(Mode.CTOR_FIELD_SELECT),mode=Mode.CTOR_FIELD_RECORD,x=c.read['operand']['value'])
    field_record=at_mode(Mode.CTOR_FIELD_RECORD);valid=c.AND(ptr(a),ptr(b))
    c.stop(c.AND(field_record,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    wide=c.g.add(c.g.fit(r['free'],c.width+1),c.g.const(2,c.width+1));enough=c.NOT(c.g.lt(c.g.const(c.cfg.heap,c.width+1),wide))
    c.stop(c.AND(field_record,valid,c.NOT(enough)),Outcome.RESOURCE,Reason.HEAP)
    field_record=c.AND(field_record,valid,enough)
    c.write('heap',field_record,r['free'],(CellTag.CONSTRUCTOR_FIELD,r['x'],r['ctor_recursive'],r['ctor_field_count']))
    c.emit(field_record,free=c.add(r['free'],1),ctor_field_info=r['free'],mode=Mode.CTOR_FIELD_LINK,x=r['ctor_field_tail'])
    link=at_mode(Mode.CTOR_FIELD_LINK)
    c.write('heap',link,r['free'],(CellTag.VECTOR_CELL,r['ctor_field_info'],r['ctor_field_rev'],0))
    c.emit(link,free=c.add(r['free'],1),ctor_field_rev=r['free'],ctor_field_count=c.add(r['ctor_field_count'],1),mode=Mode.CTOR_FIELDS)
    store=at_mode(Mode.CTOR_STORE_META)
    wide=c.g.add(c.g.fit(r['free'],c.width+1),c.g.const(3,c.width+1));enough=c.NOT(c.g.lt(c.g.const(c.cfg.heap,c.width+1),wide))
    c.stop(c.AND(store,c.NOT(enough)),Outcome.RESOURCE,Reason.HEAP)
    store=c.AND(store,enough)
    c.write('heap',store,r['free'],(CellTag.CONSTRUCTOR_ANALYSIS,r['ctor_family_signature'],r['ctor_field_vector'],r['ctor_result_args']))
    c.emit(store,free=c.add(r['free'],1),ctor_meta=r['free'],mode=Mode.CTOR_STORE_PENDING)
    pending=at_mode(Mode.CTOR_STORE_PENDING)
    c.write('heap',pending,r['free'],(CellTag.PENDING_CONSTRUCTOR,r['ctor_symbol'],r['ctor_type'],r['ctor_meta']))
    c.emit(pending,free=c.add(r['free'],1),ctor_pending=r['free'],mode=Mode.CTOR_LINK)
    link=at_mode(Mode.CTOR_LINK);more=c.lt(1,r['ctor_remaining'])
    c.write('heap',link,r['free'],(CellTag.VECTOR_CELL,r['ctor_pending'],r['ctor_names'],0))
    c.emit(link,free=c.add(r['free'],1),ctor_names=r['free'],ctor_remaining=c.sub(r['ctor_remaining'],1))
    c.emit(c.AND(link,more),mode=Mode.CTOR_CELL,x=r['ctor_next'])
    family_done(c.AND(link,c.NOT(more)),r['free'])
