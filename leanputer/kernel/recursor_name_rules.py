"""Lower arbitrary structured-name prefix comparison and genuine 'rec' suffix."""
from .native_cells import CellTag,VectorKind
from .traversal_machine import (Mode,Task,Outcome,Reason,CALL_RECNAME_PARENT,
    CALL_RECNAME_CANDIDATE,CALL_RECNAME_COMPONENT)

PRIVATE_PHASES=(CALL_RECNAME_PARENT,CALL_RECNAME_CANDIDATE,CALL_RECNAME_COMPONENT)


def emit_rules(c):
    r,n,f=c.r,c.read['node'],c.read['frame'];a,b=n['a'],n['b'];top=c.sub(r['sp'],1)
    returning=c.AND(c.mode(Mode.RETURN),c.NOT(c.eq(r['sp'],0)))
    at=lambda phase:c.AND(returning,c.eq(f['phase'],phase))
    def done(guard,value):c.emit(guard,sp=top);c.ret(guard,value)
    parent=at(CALL_RECNAME_PARENT)
    c.emit(parent,recname_parent_path=r['r'],task=Task.GET_NAME_PATH,mode=Mode.WALK,x=r['symbols_root'],query_symbol=r['name_candidate_symbol'])
    c.write('stack',parent,top,(CALL_RECNAME_CANDIDATE,0,0,Task.CHECK_RECURSOR_NAME,0,0))
    c.emit(at(CALL_RECNAME_CANDIDATE),task=Task.CHECK_RECURSOR_NAME,mode=Mode.RECNAME_LEFT_HEADER,x=r['recname_parent_path'],recname_candidate_path=r['r'])
    compared=at(CALL_RECNAME_COMPONENT);more=c.lt(1,r['recname_remaining'])
    done(c.AND(compared,c.eq(r['r'],0)),0)
    c.emit(c.AND(compared,c.NOT(c.eq(r['r'],0)),more),task=Task.CHECK_RECURSOR_NAME,mode=Mode.RECNAME_LEFT_CELL,
        x=r['recname_next_left'],recname_right=r['recname_next_right'],recname_remaining=c.sub(r['recname_remaining'],1))
    c.emit(c.AND(compared,c.NOT(c.eq(r['r'],0)),c.NOT(more)),task=Task.CHECK_RECURSOR_NAME,mode=Mode.RECNAME_SUFFIX_CELL,x=r['recname_next_right'],recname_remaining=0)
    active=c.task(Task.CHECK_RECURSOR_NAME);at_mode=lambda m:c.AND(active,c.mode(m));wb=lambda w:c.mux(c.eq(w,0),0,1)
    init=at_mode(Mode.WALK);room=c.lt(r['sp'],c.cfg.stack)
    c.stop(c.AND(init,c.NOT(room)),Outcome.RESOURCE,Reason.STACK)
    init=c.AND(init,room)
    c.write('stack',init,r['sp'],(CALL_RECNAME_PARENT,0,0,Task.CHECK_RECURSOR_NAME,0,0))
    c.emit(init,sp=c.add(r['sp'],1),task=Task.GET_NAME_PATH,x=r['symbols_root'],query_symbol=r['name_parent_symbol'])
    left=at_mode(Mode.RECNAME_LEFT_HEADER);valid=c.AND(c.eq(n['c'],VectorKind.REFERENCES),c.eq(wb(a),wb(b)))
    c.stop(c.AND(left,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(left,valid),mode=Mode.RECNAME_RIGHT_HEADER,x=r['recname_candidate_path'],recname_length=a,recname_head=b)
    right=at_mode(Mode.RECNAME_RIGHT_HEADER);shape=c.AND(c.eq(n['c'],VectorKind.REFERENCES),c.eq(wb(a),wb(b)))
    c.stop(c.AND(right,c.NOT(shape)),Outcome.INVALID,Reason.SYNTAX)
    wide=c.g.add(c.g.fit(r['recname_length'],c.width+1),c.g.const(1,c.width+1));length=c.g.eq(c.g.fit(a,c.width+1),wide)
    done(c.AND(right,shape,c.NOT(length)),0)
    c.emit(c.AND(right,shape,length),mode=c.mux(c.eq(r['recname_length'],0),Mode.RECNAME_SUFFIX_CELL,Mode.RECNAME_LEFT_CELL),
        x=c.mux(c.eq(r['recname_length'],0),b,r['recname_head']),recname_remaining=r['recname_length'],recname_right=b)
    cell=at_mode(Mode.RECNAME_LEFT_CELL);shape=c.AND(c.NOT(c.eq(r['recname_remaining'],0)),c.eq(wb(b),c.mux(more,1,0)))
    c.stop(c.AND(cell,c.NOT(shape)),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(cell,shape),mode=Mode.RECNAME_RIGHT_CELL,x=r['recname_right'],recname_next_left=b,recname_part_left=a)
    right=at_mode(Mode.RECNAME_RIGHT_CELL)
    c.stop(c.AND(right,c.eq(b,0)),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(right,c.NOT(c.eq(b,0))),mode=Mode.RECNAME_LEFT_PART,x=r['recname_part_left'],recname_next_right=b,recname_part_right=a)
    c.emit(at_mode(Mode.RECNAME_LEFT_PART),mode=Mode.RECNAME_RIGHT_PART,x=r['recname_part_right'],recname_part_tag=n['tag'],recname_part_value=a)
    right=at_mode(Mode.RECNAME_RIGHT_PART);same=c.eq(n['tag'],r['recname_part_tag'])
    done(c.AND(right,c.NOT(same)),0)
    c.write('stack',c.AND(right,same),top,(CALL_RECNAME_COMPONENT,0,0,Task.CHECK_RECURSOR_NAME,0,0))
    c.emit(c.AND(right,same),task=Task.VECTOR_EQUAL,mode=Mode.WALK,x=r['recname_part_value'],peer=a,
        vector_expected_role=c.mux(c.tag(CellTag.NAME_STRING),VectorKind.BYTES,VectorKind.LIMBS))
    suffix=at_mode(Mode.RECNAME_SUFFIX_CELL)
    c.stop(c.AND(suffix,c.NOT(c.eq(b,0))),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(suffix,c.eq(b,0)),mode=Mode.RECNAME_SUFFIX_PART,x=a)
    part=at_mode(Mode.RECNAME_SUFFIX_PART)
    done(c.AND(part,c.tag(CellTag.NAME_NUMERAL)),0)
    c.emit(c.AND(part,c.tag(CellTag.NAME_STRING)),mode=Mode.RECNAME_SUFFIX_HEADER,x=a)
    header=at_mode(Mode.RECNAME_SUFFIX_HEADER);shape=c.AND(c.eq(n['c'],VectorKind.BYTES),c.eq(wb(a),wb(b)))
    c.stop(c.AND(header,c.NOT(shape)),Outcome.INVALID,Reason.SYNTAX)
    done(c.AND(header,shape,c.NOT(c.eq(a,3))),0)
    c.emit(c.AND(header,shape,c.eq(a,3)),mode=Mode.RECNAME_SUFFIX_BYTE,x=b,recname_byte_index=0)
    byte=at_mode(Mode.RECNAME_SUFFIX_BYTE);more=c.lt(r['recname_byte_index'],2)
    shape=c.AND(c.lt(r['recname_byte_index'],3),c.eq(wb(b),c.mux(more,1,0)))
    c.stop(c.AND(byte,c.NOT(shape)),Outcome.INVALID,Reason.SYNTAX)
    byte=c.AND(byte,shape);expected=c.mux(c.eq(r['recname_byte_index'],0),114,c.mux(c.eq(r['recname_byte_index'],1),101,99))
    equal=c.eq(a,expected)
    done(c.AND(byte,c.NOT(equal)),0)
    done(c.AND(byte,equal,c.NOT(more)),1)
    c.emit(c.AND(byte,equal,more),x=b,recname_byte_index=c.add(r['recname_byte_index'],1))
