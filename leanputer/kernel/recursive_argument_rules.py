"""Lower general functional-prefix/recursive-index template derivation."""
from .arena import Tag
from .native_cells import CellTag
from .traversal_machine import (Mode,Task,Outcome,Reason,CALL_REC_WHNF,CALL_REC_DOMAIN,
    CALL_REC_OPEN,CALL_REC_APPLICATION,CALL_REC_INDEX,CALL_REC_REVERSE_INDICES,CALL_REC_REVERSE_PREFIX)

PRIVATE_PHASES=tuple(range(CALL_REC_WHNF,CALL_REC_REVERSE_PREFIX+1))


def emit_rules(c):
    r,n,f=c.r,c.read['node'],c.read['frame'];top=c.sub(r['sp'],1)
    returning=c.AND(c.mode(Mode.RETURN),c.NOT(c.eq(r['sp'],0)))
    at=lambda phase:c.AND(returning,c.eq(f['phase'],phase))
    def call(guard,phase,task,x,mode=Mode.WALK,original=0,**updates):
        c.write('stack',guard,top,(phase,original,f['depth'],Task.RECURSIVE_ARGUMENT,0,0))
        c.emit(guard,task=task,mode=mode,x=x,depth=0,**updates)
    c.emit(at(CALL_REC_WHNF),task=Task.RECURSIVE_ARGUMENT,mode=Mode.RECURSIVE_NODE,x=r['r'])
    c.emit(at(CALL_REC_DOMAIN),task=Task.RECURSIVE_ARGUMENT,mode=Mode.RECURSIVE_CAPTURE,x=f['original'])
    call(at(CALL_REC_OPEN),CALL_REC_WHNF,Task.BETA_ZETA,r['r'],Mode.BETA_ZETA)
    application=at(CALL_REC_APPLICATION);found=c.NOT(c.eq(r['r'],0))
    c.emit(c.AND(application,c.NOT(found)),sp=top,task=Task.RECURSIVE_ARGUMENT,ctx=f['depth'])
    c.ret(c.AND(application,c.NOT(found)),0)
    valid=c.AND(application,found);params=c.sub(r['header_parameter_end'],r['header_parameter_base']);indices=c.sub(r['app_arity'],params)
    c.emit(valid,recursive_family=r['r'],recursive_skip=params,recursive_indices=indices,recursive_index_remaining=indices,recursive_index_rev=0)
    have_params=c.NOT(c.eq(params,0));have_indices=c.NOT(c.eq(indices,0))
    c.emit(c.AND(valid,have_params),task=Task.RECURSIVE_ARGUMENT,mode=Mode.RECURSIVE_SKIP,x=r['app_args'])
    c.emit(c.AND(valid,c.NOT(have_params),have_indices),task=Task.RECURSIVE_ARGUMENT,mode=Mode.RECURSIVE_INDEX,x=r['app_args'])
    call(c.AND(valid,c.NOT(have_params),c.NOT(have_indices)),CALL_REC_REVERSE_INDICES,Task.REVERSE_LIST,0,reverse_length=0)
    c.emit(at(CALL_REC_INDEX),task=Task.RECURSIVE_ARGUMENT,mode=Mode.RECURSIVE_INDEX_STORE)
    c.emit(at(CALL_REC_REVERSE_INDICES),recursive_index_vector=r['r'])
    call(at(CALL_REC_REVERSE_INDICES),CALL_REC_REVERSE_PREFIX,Task.REVERSE_LIST,r['recursive_prefix_rev'],reverse_length=r['recursive_prefix_count'])
    finish=at(CALL_REC_REVERSE_PREFIX)
    c.emit(finish,sp=top,task=Task.RECURSIVE_ARGUMENT,ctx=f['depth'])
    c.alloc(finish,(CellTag.RECURSIVE_ARGUMENT,r['recursive_family'],r['r'],r['recursive_index_vector']))
    active=c.task(Task.RECURSIVE_ARGUMENT);at_mode=lambda mode:c.AND(active,c.mode(mode))
    init=at_mode(Mode.WALK);room=c.lt(r['sp'],c.cfg.stack)
    c.stop(c.AND(init,c.NOT(room)),Outcome.RESOURCE,Reason.STACK)
    begin=c.AND(init,room)
    c.write('stack',begin,r['sp'],(CALL_REC_WHNF,0,r['ctx'],Task.RECURSIVE_ARGUMENT,0,0))
    c.emit(begin,sp=c.add(r['sp'],1),task=Task.BETA_ZETA,mode=Mode.BETA_ZETA,recursive_mark=r['ctx'],recursive_prefix_rev=0,recursive_prefix_count=0)
    node=at_mode(Mode.RECURSIVE_NODE);pi=c.tag(Tag.PI)
    call(c.AND(node,pi),CALL_REC_DOMAIN,Task.ABSTRACT_SCOPE,n['a'],original=r['x'],abstract_base=r['recursive_mark'],abstract_end=r['ctx'])
    call(c.AND(node,c.NOT(pi)),CALL_REC_APPLICATION,Task.FAMILY_APPLICATION,r['x'])
    capture=at_mode(Mode.RECURSIVE_CAPTURE)
    c.stop(c.AND(capture,c.NOT(pi)),Outcome.INVALID,Reason.SYNTAX)
    wide=c.g.add(c.g.fit(r['free'],c.width+1),c.g.const(2,c.width+1))
    enough=c.NOT(c.g.lt(c.g.const(c.cfg.heap,c.width+1),wide))
    c.stop(c.AND(capture,pi,c.NOT(enough)),Outcome.RESOURCE,Reason.HEAP)
    store=c.AND(capture,pi,enough)
    c.write('heap',store,r['free'],(CellTag.PREFIX_BINDER,r['r'],n['c'],0))
    c.emit(store,free=c.add(r['free'],1),recursive_prefix_value=r['free'],mode=Mode.RECURSIVE_PREFIX_LINK)
    link=at_mode(Mode.RECURSIVE_PREFIX_LINK)
    c.write('heap',link,r['free'],(CellTag.VECTOR_CELL,r['recursive_prefix_value'],r['recursive_prefix_rev'],0))
    c.emit(link,free=c.add(r['free'],1),recursive_prefix_rev=r['free'],recursive_prefix_count=c.add(r['recursive_prefix_count'],1))
    call(link,CALL_REC_OPEN,Task.OPEN_TELESCOPE,r['x'],Mode.TELESCOPE,open_tag=Tag.PI,bounded=1,limit=c.add(r['ctx'],1))
    skip=at_mode(Mode.RECURSIVE_SKIP);many=c.lt(1,r['recursive_skip'])
    c.stop(c.AND(skip,c.eq(r['recursive_skip'],0)),Outcome.INVALID,Reason.SYNTAX)
    c.emit(c.AND(skip,many),recursive_skip=c.sub(r['recursive_skip'],1),x=n['b'])
    last=c.AND(skip,c.eq(r['recursive_skip'],1));has_indices=c.NOT(c.eq(r['recursive_indices'],0))
    c.emit(c.AND(last,has_indices),recursive_skip=0,mode=Mode.RECURSIVE_INDEX,x=n['b'])
    call(c.AND(last,c.NOT(has_indices)),CALL_REC_REVERSE_INDICES,Task.REVERSE_LIST,0,reverse_length=0)
    index=at_mode(Mode.RECURSIVE_INDEX);more=c.lt(1,r['recursive_index_remaining'])
    valid=c.AND(c.NOT(c.eq(r['recursive_index_remaining'],0)),c.eq(c.mux(c.eq(n['b'],0),0,1),c.mux(more,1,0)))
    c.stop(c.AND(index,c.NOT(valid)),Outcome.INVALID,Reason.SYNTAX)
    index=c.AND(index,valid)
    c.emit(index,recursive_index_next=n['b'])
    call(index,CALL_REC_INDEX,Task.ABSTRACT_SCOPE,n['a'],abstract_base=r['recursive_mark'],abstract_end=r['ctx'])
    index_store=at_mode(Mode.RECURSIVE_INDEX_STORE);room=c.lt(r['free'],c.cfg.heap)
    c.stop(c.AND(index_store,c.NOT(room)),Outcome.RESOURCE,Reason.HEAP)
    index_store=c.AND(index_store,room)
    c.write('heap',index_store,r['free'],(CellTag.VECTOR_CELL,r['r'],r['recursive_index_rev'],0))
    c.emit(index_store,free=c.add(r['free'],1),recursive_index_rev=r['free'],recursive_index_remaining=c.sub(r['recursive_index_remaining'],1))
    c.emit(c.AND(index_store,more),mode=Mode.RECURSIVE_INDEX,x=r['recursive_index_next'])
    call(c.AND(index_store,c.NOT(more)),CALL_REC_REVERSE_INDICES,Task.REVERSE_LIST,r['free'],reverse_length=r['recursive_indices'])
